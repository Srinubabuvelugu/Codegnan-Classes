-- GET WEATHER THE NUMBER IS EVEN OR ODD

DELIMITER //
CREATE PROCEDURE EVEN_OR_ODD(IN NUM INT)
BEGIN 

	IF NUM % 2 = 0 THEN 
		SELECT "EVEN";
	ELSE 
		SELECT "ODD";
	END IF;
END //
DELIMITER ;

